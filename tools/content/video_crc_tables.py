"""Regenerate the immutable PVID CRC concatenation matrices on the host."""
from pathlib import Path


def generate() -> str:
    # Reflected IEEE CRC32, one zero byte applied to each basis vector.
    matrix = []
    for bit in range(32):
        value = 1 << bit
        for _ in range(8):
            value = (value >> 1) ^ (0xEDB88320 if value & 1 else 0)
        matrix.append(value)
    rows = []
    for _ in range(17):
        rows.append(matrix)
        squared = []
        for value in matrix:
            result = 0
            for bit in range(32):
                if value & (1 << bit):
                    result ^= matrix[bit]
            squared.append(result)
        matrix = squared
    lines = [
        "/* Generated by tools/content/video_crc_tables.py; do not edit.",
        " * Row k shifts a finalized IEEE CRC32 by 2^k bytes for concatenation.",
        " * Ordinary read-only storage: no IRAM table or runtime initialization. */",
        "static const uint32_t video_crc_shift[17][32] = {",
    ]
    for row in rows:
        lines.append("    {")
        for at in range(0, 32, 8):
            lines.append("        " + ",".join(f"0x{x:08x}u" for x in row[at:at + 8]) + ",")
        lines.append("    },")
    lines.extend(["};", "_Static_assert(sizeof(video_crc_shift)==2176u,\"video CRC table budget\");", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    output = Path(__file__).resolve().parents[2] / "services/video/crc_shift_table.h"
    output.write_text(generate(), encoding="ascii", newline="\n")
